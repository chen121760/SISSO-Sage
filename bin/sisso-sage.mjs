#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { analyzeDirectory, buildBundle, paretoModels, selectModels } from "../src/analysis.mjs";
import { CAPABILITIES } from "../src/capabilities.mjs";
import { featureMetadataTemplate } from "../src/metadata.mjs";
import {
  comparisonResult,
  featureContextResult,
  inspectionResult,
  leakageResult,
  listModelsResult,
  modelResult,
} from "../src/service.mjs";

function parseArgs(argv) {
  const positional = [];
  const options = {};
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i];
    if (!token.startsWith("--")) { positional.push(token); continue; }
    const [rawKey, inline] = token.slice(2).split("=", 2);
    const key = rawKey.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
    if (inline !== undefined) options[key] = inline;
    else if (argv[i + 1] && !argv[i + 1].startsWith("--")) options[key] = argv[++i];
    else options[key] = true;
  }
  return { positional, options };
}

function usage() {
  return `SISSO-Sage — AI-ready SISSO analysis

Usage:
  sisso-sage inspect <run-dir|run.tar.gz> [--features sage.features.json] [--verify verify.dat]
  sisso-sage leakage <run> [--verify verify.dat]
  sisso-sage models <run> [--limit 20] [--sort verify.rmse] [--feature name]
  sisso-sage model <run> --rank 1
  sisso-sage compare <run> --ranks 1,2,3
  sisso-sage pareto <run> [--dataset verify] [--metric rmse]
  sisso-sage select <run> [--limit 5] [--dataset verify] [--metric rmse]
  sisso-sage bundle <run> --output analysis.bundle.json
  sisso-sage metadata-template <run> [--output sage.features.json]
  sisso-sage feature-doc <run> [--output FEATURES.md]
  sisso-sage feature-context <run> --feature name --source-root /path/to/source
  sisso-sage capabilities

Metadata options:
  --features <json>            Explicit sage.features.json (JSON, not CSV)
  --source-root <dir>          Auto-find feature dictionary and rename map
  --feature-dictionary <csv>   Explicit feature dictionary CSV; readable columns:
                               feature, note, unit, group, source
  --rename-map <csv>           Old-to-new feature-name mapping; columns: old, new

Notes:
  --limit accepts any positive integer (hard cap 100000). Responses carry
  "returned", "limit" and "truncated" so a truncated list is never silent.

All data commands emit JSON. Use --compact for token-efficient output.`;
}

function printJson(value, compact = false) {
  process.stdout.write(`${JSON.stringify(value, null, compact ? 0 : 2)}\n`);
}

function analysisOptions(options) {
  return {
    featuresFile: options.features,
    topFile: options.topFile,
    verifyFile: options.verify,
    sourceRoot: options.sourceRoot,
    dictionaryFile: options.featureDictionary,
    renameMapFile: options.renameMap,
  };
}

function featureDocument(analysis) {
  const clean = (value) => String(value ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
  const lines = [
    "# SISSO feature evidence",
    "",
    "> Generated by SISSO-Sage. `ai-draft` and `needs-user-confirmation` entries must not be treated as established physical definitions.",
    "",
    `Run: \`${clean(analysis.discovery.root)}\``,
    "",
    "| Feature | Unit/class | Category | Review status | Description | Source |",
    "|---|---|---|---|---|---|",
  ];
  for (const column of analysis.result.columns.slice(2)) {
    const name = column.original;
    const meta = analysis.featureMetadata.features[name] || {};
    const source = meta.source?.file || meta.source?.label || meta.source?.root || "";
    lines.push(`| ${clean(name)} | ${clean(meta.unit)} | ${clean(meta.category)} | ${clean(meta.reviewStatus || "needs-user-confirmation")} | ${clean(meta.description)} | ${clean(source)} |`);
  }
  lines.push("", "## Review rule", "", "Ambiguous names require either the original extraction source or a researcher-confirmed definition. AI-written explanations must remain marked `ai-draft` until confirmed.", "");
  return lines.join("\n");
}

async function main() {
  const { positional, options } = parseArgs(process.argv.slice(2));
  const command = positional[0];
  if (!command || command === "help" || options.help) { process.stdout.write(`${usage()}\n`); return; }
  if (command === "capabilities") { printJson(CAPABILITIES, options.compact); return; }

  const directory = positional[1];
  if (!directory) throw new Error(`Missing run directory.\n\n${usage()}`);
  const analysis = analyzeDirectory(directory, analysisOptions(options));

  if (command === "inspect") {
    printJson(inspectionResult(analysis), options.compact);
    return;
  }
  if (command === "leakage") {
    printJson(leakageResult(analysis), options.compact);
    return;
  }
  if (command === "models") {
    printJson(listModelsResult(analysis, options), options.compact);
    return;
  }
  if (command === "model") {
    printJson(modelResult(analysis, options.rank), options.compact);
    return;
  }
  if (command === "compare") {
    const ranks = String(options.ranks || "").split(",").map(Number).filter(Number.isFinite);
    printJson(comparisonResult(analysis, ranks), options.compact);
    return;
  }
  if (command === "pareto") {
    printJson({ kind: "sisso-sage-pareto", ...paretoModels(analysis.result, { dataset: options.dataset, metric: options.metric }) }, options.compact);
    return;
  }
  if (command === "select") {
    printJson({ kind: "sisso-sage-selection", ...selectModels(analysis.result, analysis.summaries, { dataset: options.dataset, metric: options.metric, limit: options.limit }) }, options.compact);
    return;
  }
  if (command === "bundle") {
    const output = path.resolve(options.output || "sisso-sage.bundle.json");
    const bundle = buildBundle(analysis, { dataset: options.dataset, metric: options.metric, limit: options.limit });
    fs.writeFileSync(output, `${JSON.stringify(bundle, null, options.compact ? 0 : 2)}\n`, "utf8");
    printJson({ kind: "sisso-sage-bundle-written", output, models: bundle.models.length, schemaVersion: bundle.schemaVersion }, options.compact);
    return;
  }
  if (command === "metadata-template") {
    const output = path.resolve(options.output || path.join(directory, "sage.features.json"));
    const names = analysis.result.columns.slice(2).map((column) => column.original);
    fs.writeFileSync(output, `${JSON.stringify(featureMetadataTemplate(names, analysis.featureMetadata.features), null, 2)}\n`, "utf8");
    printJson({ kind: "sisso-sage-metadata-template-written", output, features: names.length }, options.compact);
    return;
  }
  if (command === "feature-doc") {
    const output = path.resolve(options.output || "FEATURES.md");
    fs.writeFileSync(output, featureDocument(analysis), "utf8");
    const unresolved = Object.values(analysis.featureMetadata.features).filter((item) => ["needs-user-confirmation", "unit-manifest-only", "ai-draft"].includes(item.reviewStatus)).length;
    printJson({ kind: "sisso-sage-feature-doc-written", output, features: analysis.result.meta.nFeatures, unresolved }, options.compact);
    return;
  }
  if (command === "feature-context") {
    const feature = String(options.feature || "");
    printJson(featureContextResult(analysis, feature, { sourceRoot: options.sourceRoot, limit: options.limit }), options.compact);
    return;
  }
  throw new Error(`Unknown command: ${command}\n\n${usage()}`);
}

main().catch((error) => {
  const payload = { kind: "sisso-sage-error", error: error.message, health: error.health || undefined };
  process.stderr.write(`${JSON.stringify(payload, null, 2)}\n`);
  process.exitCode = 1;
});
